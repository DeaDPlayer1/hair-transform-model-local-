    def test_stage2_roi_seamless_clone_paste_back(self):
        """Test that seamlessClone executes smoothly without hard seam boundaries."""
        import cv2

        h_full, w_full = 200, 200
        base_np = np.full((h_full, w_full, 3), 120, dtype=np.uint8)
        crop_w, crop_h = 60, 60
        crop_x1, crop_y1 = 70, 70

        crop_restored_np = np.full((crop_h, crop_w, 3), 140, dtype=np.uint8)
        crop_restored_np[15:45, 15:45] = 160

        clone_mask = np.zeros((crop_h, crop_w), dtype=np.uint8)
        clone_mask[15:45, 15:45] = 255

        ys_m, xs_m = np.where(clone_mask > 0)
        touches_border = (
            ys_m.min() <= 1 or xs_m.min() <= 1
            or ys_m.max() >= clone_mask.shape[0] - 2
            or xs_m.max() >= clone_mask.shape[1] - 2
        )
        self.assertFalse(touches_border)

        center = (
            int(crop_x1 + (xs_m.min() + xs_m.max()) / 2),
            int(crop_y1 + (ys_m.min() + ys_m.max()) / 2),
        )
        cloned_np = cv2.seamlessClone(
            crop_restored_np, base_np, clone_mask, center, cv2.NORMAL_CLONE,
        )
        self.assertEqual(cloned_np.shape, (h_full, w_full, 3))
        self.assertTrue(np.all(np.isfinite(cloned_np)))
        # Outside ROI crop should remain identical to base
        self.assertTrue(np.array_equal(cloned_np[:50, :50], base_np[:50, :50]))

