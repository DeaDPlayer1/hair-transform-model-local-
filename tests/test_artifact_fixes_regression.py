    def test_harmonize_preserves_chroma_when_match_chroma_false(self):
        """Test that harmonize_hair_color leaves a* and b* channels untouched on bald-base when match_chroma=False."""
        import cv2
        from src.hairstyle_alignment import harmonize_hair_color

        h, w = 64, 64
        # Vivid auburn/red hair
        ref_rgb = np.zeros((h, w, 3), dtype=np.uint8)
        ref_rgb[:, :] = [160, 50, 30]
        alpha = np.ones((h, w), dtype=np.float32)

        # Target is bald with warm skin
        target_rgb = np.full((h, w, 3), (230, 190, 160), dtype=np.uint8)
        empty_tgt_mask = np.zeros((h, w), dtype=np.uint8)

        harmonized = harmonize_hair_color(
            aligned_hair_rgb=ref_rgb,
            aligned_hair_alpha=alpha,
            target_rgb=target_rgb,
            target_hair_mask_np=empty_tgt_mask,
            strength=0.20,
            match_chroma=False,
        )

        ref_lab = cv2.cvtColor(cv2.cvtColor(ref_rgb, cv2.COLOR_RGB2BGR), cv2.COLOR_BGR2LAB)
        harm_lab = cv2.cvtColor(cv2.cvtColor(harmonized, cv2.COLOR_RGB2BGR), cv2.COLOR_BGR2LAB)

        # Chroma a* and b* channels MUST be identical (within 1 unit rounding)
        np.testing.assert_allclose(harm_lab[:, :, 1], ref_lab[:, :, 1], atol=1.0)
        np.testing.assert_allclose(harm_lab[:, :, 2], ref_lab[:, :, 2], atol=1.0)

    def test_soft_hair_prob_fringe_catch_widens_mask(self):
        """Test that build_bald_edit_mask catches low-confidence wisps near hair, but ignores distant noise."""
        from src.bald_converter import BaldConverterConfig, SDInpaintBaldConverter
        import cv2

        config = BaldConverterConfig()
        converter = SDInpaintBaldConverter(config, pipeline="dummy")

        h, w = 256, 256
        target_img = Image.new("RGB", (w, h), color=(200, 180, 160))
        # Base hair mask: block from y=30..80, x=80..176
        hair_mask_np = np.zeros((h, w), dtype=np.uint8)
        hair_mask_np[30:80, 80:176] = 255
        hair_mask = Image.fromarray(hair_mask_np, mode="L")

        # Hair probability map:
        # 1. Near hair (y=80..95, x=80..176): prob = 0.35 (whispy fringe strand)
        # 2. Far from hair (y=200..230, x=80..176): prob = 0.40 (isolated false positive)
        hair_prob = np.zeros((h, w), dtype=np.float32)
        hair_prob[80:95, 80:176] = 0.35
        hair_prob[200:230, 80:176] = 0.40

        # Run without hair_prob
        edit_mask_no_prob, _, _ = converter.build_bald_edit_mask(
            target_image=target_img,
            target_hair_mask=hair_mask,
            hair_prob=None,
        )
        edit_no_prob_np = np.asarray(edit_mask_no_prob)

        # Run with hair_prob
        edit_mask_with_prob, _, _ = converter.build_bald_edit_mask(
            target_image=target_img,
            target_hair_mask=hair_mask,
            hair_prob=hair_prob,
        )
        edit_with_prob_np = np.asarray(edit_mask_with_prob)

        # Near hair fringe (y=85, x=100) should be included in with_prob
        self.assertEqual(edit_with_prob_np[85, 100], 255)
        # Distant false positive (y=215, x=100) must NOT be included (remains 0)
        self.assertEqual(edit_with_prob_np[215, 100], 0)
        # Overall edit mask with hair_prob should have captured more pixels
        self.assertGreater(np.count_nonzero(edit_with_prob_np), np.count_nonzero(edit_no_prob_np))

