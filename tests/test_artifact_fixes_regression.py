    def test_ear_alpha_weighted_blend(self):
        """Test that soft donor hair over ears blends with target skin rather than cutting over."""
        from src.hairstyle_alignment import EAR_SEG_CLASSES

        h_t, w_t = 100, 100
        orig_target_np = np.full((h_t, w_t, 3), 200, dtype=np.uint8) # Original skin = 200
        final_np = np.full((h_t, w_t, 3), 50, dtype=np.uint8)        # Inpainted/hair = 50

        ident_np = np.zeros((h_t, w_t), dtype=np.uint8)
        ident_np[40:60, 40:60] = 255 # ear region protected

        bald_seg_map = np.zeros((h_t, w_t), dtype=np.int64)
        ear_class = list(EAR_SEG_CLASSES)[0]
        bald_seg_map[40:60, 40:60] = ear_class

        aligned_donor_alpha = np.zeros((h_t, w_t), dtype=np.float32)
        # Low alpha region: 0.25 (previously hard-cut to 50)
        aligned_donor_alpha[40:50, 40:60] = 0.25
        # High alpha region: 0.80 (opaque hair)
        aligned_donor_alpha[50:60, 40:60] = 0.80

        face_core_protection = ident_np.copy()
        ear_cartilage_mask = np.isin(bald_seg_map, EAR_SEG_CLASSES)
        ear_alpha = np.clip(aligned_donor_alpha, 0.0, 1.0)
        EAR_HAIR_OPAQUE = 0.55

        hard_hair_over_ears = ear_cartilage_mask & (ear_alpha >= EAR_HAIR_OPAQUE)
        face_core_protection[hard_hair_over_ears] = 0

        soft_ear_band = ear_cartilage_mask & (ear_alpha > 0.0) & (ear_alpha < EAR_HAIR_OPAQUE)
        if np.any(soft_ear_band):
            blend_w = (ear_alpha[soft_ear_band] / EAR_HAIR_OPAQUE)[..., None]
            final_np[soft_ear_band] = (
                orig_target_np[soft_ear_band].astype(np.float32) * (1.0 - blend_w)
                + final_np[soft_ear_band].astype(np.float32) * blend_w
            ).clip(0, 255).astype(np.uint8)
            face_core_protection[soft_ear_band] = 0

        final_np[face_core_protection > 0] = orig_target_np[face_core_protection > 0]

        # The low alpha band (0.25) should be blended between 200 and 50
        # blend_w = 0.25 / 0.55 ~ 0.4545 -> expected ~ 200*(1-0.4545) + 50*0.4545 ~ 131.8
        low_val = final_np[45, 50, 0]
        self.assertTrue(100 < low_val < 160)

        # The high alpha band (0.80) should be pure hair (50)
        high_val = final_np[55, 50, 0]
        self.assertEqual(high_val, 50)


